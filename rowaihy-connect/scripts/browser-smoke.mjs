import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import http from 'node:http';
import { mkdir } from 'node:fs/promises';
import { createHub } from '../src/server.mjs';
const fixture=http.createServer((_req,res)=>{res.setHeader('Content-Type','application/json');res.end('{"ok":true}');});
await new Promise(done=>fixture.listen(0,'127.0.0.1',done));
const hub=await createHub({port:0,dbPath:':memory:'});
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
try{
  await page.goto(hub.url);
  await page.getByRole('heading',{name:'اختبر بثقة. افهم ما تغيّر.'}).waitFor();
  await page.getByRole('button',{name:'إضافة فحص ذاتي',exact:true}).click();
  await page.locator('article.project-card').getByText('ناجح',{exact:true}).waitFor();
  console.log('PASS self-check and live UI polling');
  await page.getByRole('button',{name:'+ مشروع جديد',exact:true}).click();
  const form=page.locator('#project-form');
  await form.getByLabel('اسم المشروع',{exact:true}).fill('مشروع المتصفح');
  await form.getByLabel('رابط بيئة الاختبار',{exact:true}).fill('http://127.0.0.1:'+fixture.address().port);
  await form.locator('[data-field="name"]').fill('فحص API');
  await form.locator('[data-field="path"]').fill('/health');
  await form.locator('[data-field="jsonPath"]').fill('ok');
  await form.locator('[data-field="jsonExpected"]').fill('true');
  await form.getByRole('button',{name:'حفظ المشروع',exact:true}).click();
  const card=page.locator('article.project-card').filter({has:page.getByRole('heading',{name:'مشروع المتصفح',exact:true})});
  await card.getByRole('button',{name:'تشغيل الفحوصات',exact:true}).click();
  await card.getByText('ناجح',{exact:true}).waitFor();
  console.log('PASS project creation, HTTP/JSON execution and result display');
  await card.getByRole('button',{name:'تعديل',exact:true}).click();
  await form.locator('[data-field="expectedStatus"]').fill('503');
  await form.getByRole('button',{name:'حفظ المشروع',exact:true}).click();
  await card.getByRole('button',{name:'تشغيل الفحوصات',exact:true}).click();
  await card.getByText('فشل',{exact:true}).waitFor();
  const row=page.getByRole('row').filter({hasText:'مشروع المتصفح'}).first();
  await row.getByRole('button',{name:'التفاصيل',exact:true}).click();
  await page.locator('#run-detail').getByText('× رمز HTTP',{exact:true}).waitFor();
  const downloaded=page.waitForEvent('download');
  await page.getByRole('link',{name:'تنزيل تقرير HTML',exact:true}).click();
  const download=await downloaded;
  assert.match(download.suggestedFilename(),/^rowaihy-run-.*\.html$/);
  await page.getByRole('button',{name:'إغلاق تفاصيل التشغيل',exact:true}).click();
  console.log('PASS expected failure diagnostics, dialog and downloadable report');
  await mkdir('qa',{recursive:true});
  await page.screenshot({path:'qa/desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'qa/mobile.png',fullPage:true});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Mobile page overflows horizontally');
  assert.deepEqual(errors,[],'Browser has uncaught errors');
  console.log('PASS responsive layout bounds and clean browser runtime');
}finally{
  await browser.close();await hub.close();
  await new Promise(done=>{fixture.close(done);fixture.closeAllConnections();});
}
